type Entry = {
  id: string;
  title: string;
  zhTitle: string;
  // The age span in months, and a typical session in minutes (the child's cues end it sooner).
  months: [number, number];
  minutes: [number, number];
  category: DiscoverCategory;
  area: string;
  topic: string;
  settings: ActivitySetting[];
  // Absent when it needs special or prepared materials ("Needs prep").
  materialType?: MaterialType;
  description: string;
  zhDescription: string;
  // The capacities it builds (the card's "Builds" line shows the first two).
  domains: string[];
  zhDomains: string[];
  materials: string[];
  zhMaterials: string[];
  preparation?: string;
  zhPreparation?: string;
  steps: string[];
  zhSteps: string[];
  extensions: string[];
  zhExtensions: string[];
  indirectAim: string;
  zhIndirectAim: string;
  // The whole safety note, starting with ALONE.
  safety: string;
  zhSafety: string;
  picturePrompt: string;
};

function infant(e: Entry): Activity {
  const [from, to] = e.months;
  const n = e.materials.length;
  return {
    id: e.id,
    title: e.title,
    age: `${from}–${to} months`,
    ageKey: "0–2",
    area: e.area,
    topic: e.topic,
    category: e.category,
    minutes: e.minutes[1],
    minMinutes: e.minutes[0],
    materialsLabel: n ? `${n} material${n > 1 ? "s" : ""}` : "No materials",
    image: photos[e.id] ?? placeholder,
    description: e.description,
    domains: e.domains,
    materials: e.materials,
    steps: e.steps,
    keywords: `${e.title.toLowerCase()} baby infant newborn 0-12 months`,
    safety: e.safety,
    settings: e.settings,
    ...(e.materialType ? { materialType: e.materialType } : {}),
    ...(e.preparation ? { preparation: e.preparation } : {}),
    extensions: e.extensions,
    directAim: DIRECT_AIM,
    indirectAim: e.indirectAim,
    picturePrompt: e.picturePrompt,
    zh: {
      title: e.zhTitle,
      keywords: "宝宝 婴儿 新生儿 0-1岁",
      age: `${from}–${to}个月`,
      materialsLabel: n ? `${n}种材料` : "无需材料",
      description: e.zhDescription,
      domains: e.zhDomains,
      materials: e.zhMaterials,
      steps: e.zhSteps,
      safety: e.zhSafety,
      ...(e.zhPreparation ? { preparation: e.zhPreparation } : {}),
      extensions: e.zhExtensions,
      directAim: DIRECT_AIM_ZH,
      indirectAim: e.zhIndirectAim,
    },
  };
}

