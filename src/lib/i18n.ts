// Formats a child's current age (computed from their birthdate) as a full phrase, e.g. "3 years, 2 months" / "3岁2个月".
export function childAge(child: { dob: string }, t: Copy): string {
  const { years, months } = ageFromDob(child.dob);
  if (t.code === "zh") return months > 0 ? `${years}岁${months}个月` : `${years}岁`;
  if (years === 0) return months === 1 ? "1 month" : `${months} months`;
  return months > 0 ? `${years} year${years === 1 ? "" : "s"}, ${months} month${months === 1 ? "" : "s"}` : `${years} year${years === 1 ? "" : "s"}`;
}

// Formats a child's current age as a short badge, e.g. "3y 2m" / "3岁2月".
export function childShortAge(child: { dob: string }, t: Copy): string {
  const { years, months } = ageFromDob(child.dob);
  if (t.code === "zh") return months > 0 ? `${years}岁${months}月` : `${years}岁`;
  return months > 0 ? `${years}y ${months}m` : `${years}y`;
}

export function childEnrolled(child: { enrolled: string; enrolledZh?: string }, t: Copy): string {
  return t.code === "zh" ? child.enrolledZh || child.enrolled : child.enrolled;
}

// Returns the Chinese note text when available, otherwise the stored English note.
export function noteText(notes: string | undefined, notesZh: string | undefined, t: Copy): string | undefined {
  return t.code === "zh" ? notesZh || notes : notes;
}

type ActivityLike = {
  title: string; age: string; materialsLabel: string; description: string; domains: string[]; materials: string[]; steps: string[];
  zh?: { title?: string; age?: string; materialsLabel?: string; description?: string; domains?: string[]; materials?: string[]; steps?: string[] };
};

// Returns a copy of the activity with display fields swapped to their Chinese translations when available.
export function localizeActivity<A extends ActivityLike>(a: A, t: Copy): A {
  if (t.code !== "zh" || !a.zh) return a;
  return {
    ...a,
    title: a.zh.title || a.title,
    age: a.zh.age || a.age,
    materialsLabel: a.zh.materialsLabel || a.materialsLabel,
    description: a.zh.description || a.description,
    domains: a.zh.domains || a.domains,
    materials: a.zh.materials || a.materials,
    steps: a.zh.steps || a.steps,
  };
}
